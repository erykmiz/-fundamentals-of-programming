# Zadanie 3.8: poprawienie błędów w obliczaniu średniej ocen.
# Nazwy zmiennych muszą się zgadzać, a Python odróżnia małe i wielkie litery.

math = 5  # Zapisuje ocenę z matematyki jako liczbę całkowitą.
art = 4  # Zapisuje ocenę z plastyki.
music = 5  # Zapisuje ocenę z muzyki.
history = 3  # Zapisuje ocenę z historii jako liczbę 3, zamiast tekstu '3'.
average = (math + art + music + history) / 4  # Dodaje cztery oceny, a dzięki nawiasom dzieli całą sumę przez 4.
print("Średnia ocen:", average)  # Używa poprawnej nazwy zmiennej i zgodnych cudzysłowów; wynik: 4.25.
