# Zadanie 4.1: wyświetlanie danych za pomocą f-stringów.
# Dane Adama są przykładowe; możesz zmienić je na własne.
name = "Adam"  # Zapisuje przykładowe imię jako tekst.
age = 20  # Zapisuje przykładowy wiek w latach.
height = 180  # Zapisuje przykładowy wzrost w centymetrach.
print(f"My name is {name}.")  # Wstawia wartość zmiennej name w miejsce nawiasów klamrowych.
print(f"I am {age} years old, and my height is {height} cm.")  # Wyświetla wiek i wzrost w jednym zdaniu.
print(f"In 6 years I will be {age + 6} years old.")  # Dodaje 6 do obecnego wieku i wyświetla wynik.
