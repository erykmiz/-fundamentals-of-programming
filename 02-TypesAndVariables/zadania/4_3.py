# Zadanie 4.3: wyświetlanie działań i ich wyników.
a = 3  # Zapisuje pierwszą liczbę.
b = 5  # Zapisuje drugą liczbę.
print(f"{a}+{b}={a + b}")  # Wyświetla dodawanie: 3+5=8.
print(f"{a}-{b}={a - b}")  # Wyświetla odejmowanie: 3-5=-2.
print(f"{a}*{b}={a * b}")  # Wyświetla mnożenie: 3*5=15.
print(f"{a}/{b}={a / b}")  # Wyświetla dzielenie: 3/5=0.6.
