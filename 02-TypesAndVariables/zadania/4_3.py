# Zadanie 4.3: pokazujemy cztery działania na liczbach 3 i 5 razem z wynikami.
# f przed tekstem pozwala wstawić w miejsca {} wartości zmiennych lub wyniki działań.

a = 3  # Zapamiętuje pierwszą liczbę, czyli 3, pod nazwą a.
b = 5  # Zapamiętuje drugą liczbę, czyli 5, pod nazwą b.

print(f"{a}+{b}={a + b}")  # Wstawia 3 i 5 oraz wynik dodawania, więc pokazuje 3+5=8.
print(f"{a}-{b}={a - b}")  # Odejmuje 5 od 3 i pokazuje 3-5=-2.
print(f"{a}*{b}={a * b}")  # Mnoży 3 przez 5 i pokazuje 3*5=15; * oznacza mnożenie.
print(f"{a}/{b}={a / b}")  # Dzieli 3 przez 5 i pokazuje 3/5=0.6; / oznacza dzielenie.
