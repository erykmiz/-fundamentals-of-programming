# Zadanie 5.1: pobranie imienia i nazwiska z klawiatury.
first_name = input("Enter your first name: ")  # Czeka na wpisanie imienia i zapisuje je jako tekst.
last_name = input("Enter your last name: ")  # Czeka na wpisanie nazwiska i zapisuje je jako tekst.
full_name = first_name + " " + last_name  # Łączy imię i nazwisko, dodając między nimi jedną spację.
print(f"Your first name is {first_name} and your last name is {last_name}")  # Wyświetla osobno opisane imię i nazwisko.
print(f"And your full name is {full_name}")  # Wyświetla połączone imię i nazwisko.
