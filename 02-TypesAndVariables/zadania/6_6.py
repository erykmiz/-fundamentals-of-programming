# Zadanie 6.6: numery znaków w standardzie Unicode.
print(f"a {ord('a')}")  # ord zamienia znak a na jego numer: 97.
print(f"b {ord('b')}")  # Wyświetla numer znaku b: 98.
print(f"z {ord('z')}")  # Wyświetla numer znaku z: 122.
print(f"A {ord('A')}")  # Wyświetla numer wielkiej litery A: 65.
print(f"B {ord('B')}")  # Wyświetla numer wielkiej litery B: 66.
print(f"Z {ord('Z')}")  # Wyświetla numer wielkiej litery Z: 90.
print(f"1 {ord('1')}")  # Wyświetla numer znaku cyfry 1, a nie liczbę 1: 49.
print(f"= {ord('=')}")  # Wyświetla numer znaku równości: 61.
print(f"+ {ord('+')}")  # Wyświetla numer znaku plus: 43.
print(f"€ {ord('€')}")  # Wyświetla numer znaku euro: 8364.
