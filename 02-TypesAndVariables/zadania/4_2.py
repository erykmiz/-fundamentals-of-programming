# Zadanie 4.2: dochód rodziny przypadający na jedną osobę.
father_income = 5450  # Zapisuje dochód ojca podany w zadaniu.
mother_income = 4920  # Zapisuje dochód matki podany w zadaniu.
family_members = 5  # Zapisuje liczbę osób w rodzinie.
total_income = father_income + mother_income  # Dodaje dochody rodziców: 10370.
income_per_person = total_income / family_members  # Dzieli cały dochód przez 5 osób: 2074.
print(f"Total family income is {total_income:.2f}, and income per person is {income_per_person:.2f}")  # Wyświetla oba dochody; .2f oznacza dwa miejsca po przecinku.
