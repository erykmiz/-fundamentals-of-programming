# Zadanie 3.4: przeliczamy 70 kilometrów na godzinę na metry na sekundę.
# Dzielimy przez 3.6, bo 1 km/h to 1000 m / 3600 s.

speed_kmh = 70  # Zapisuje prędkość 70 km/h pod nazwą speed_kmh.
speed_ms = speed_kmh / 3.6  # Dzieli 70 przez 3.6 i zapisuje około 19.4444 m/s pod nazwą speed_ms.
print(speed_kmh, "km/h =", speed_ms, "m/s")  # Pokazuje 70, podpis jednostki, obliczony wynik i podpis m/s.
