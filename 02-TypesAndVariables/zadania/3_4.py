# Zadanie 3.4: przeliczanie prędkości z km/h na m/s.

speed_kmh = 70  # Zapisuje prędkość 70 kilometrów na godzinę podaną w zadaniu.
speed_ms = speed_kmh / 3.6  # Dzieli przez 3.6, ponieważ kilometr ma 1000 m, a godzina 3600 s.
print(speed_kmh, "km/h =", speed_ms, "m/s")  # Wyświetla prędkość w obu jednostkach.
