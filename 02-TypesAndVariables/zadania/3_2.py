# Zadanie 3.2: obliczanie sumy trzech liczb zamiast dwóch.

number1 = 71  # Zapisuje pierwszą liczbę podaną w przykładzie.
number2 = 14  # Zapisuje drugą liczbę podaną w przykładzie.
number3 = 10  # Zapisuje przykładową trzecią liczbę, którą możesz zmienić.
result = number1 + number2 + number3  # Dodaje wszystkie trzy liczby; dla tych danych suma wynosi 95.
print("Liczba 1:", number1)  # Wyświetla wartość pierwszej liczby.
print("Liczba 2:", number2)  # Wyświetla wartość drugiej liczby.
print("Liczba 3:", number3)  # Wyświetla wartość trzeciej liczby.
print("Suma trzech liczb:", result)  # Wyświetla obliczoną sumę.
