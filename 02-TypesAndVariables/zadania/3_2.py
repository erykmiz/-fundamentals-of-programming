# Zadanie 3.2: dodajemy trzy liczby: 71, 14 oraz przykładową trzecią liczbę 10.

number1 = 71  # Zapisuje pierwszą liczbę 71 pod nazwą number1.
number2 = 14  # Zapisuje drugą liczbę 14 pod nazwą number2.
number3 = 10  # Zapisuje trzecią liczbę 10 pod nazwą number3; tę przykładową wartość można zmienić.
result = number1 + number2 + number3  # Odczytuje trzy liczby, dodaje 71 + 14 + 10 = 95 i zapisuje wynik w result.
print("Liczba 1:", number1)  # Wyświetla podpis Liczba 1: i zapamiętaną pierwszą liczbę 71.
print("Liczba 2:", number2)  # Wyświetla drugą liczbę 14 razem z jej podpisem.
print("Liczba 3:", number3)  # Wyświetla trzecią liczbę 10 razem z jej podpisem.
print("Suma trzech liczb:", result)  # Wyświetla obliczoną sumę 95, odczytując wartość result.
