# Zadanie 1.2: przykład działania if i else.
age = 20  # Zapisuje przykładowy wiek; możesz zmienić go, aby sprawdzić drugą możliwość.
if age >= 18:  # Sprawdza, czy wiek wynosi co najmniej 18 lat.
    print('You are an adult')  # Wykonuje tę linię tylko wtedy, gdy warunek jest prawdziwy.
else:  # Wybiera tę część, gdy warunek age >= 18 jest fałszywy.
    print('You are not an adult')  # Wyświetla komunikat dla wieku poniżej 18 lat.
