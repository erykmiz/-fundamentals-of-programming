# Zadanie 1.2: przykład działania if i else.
# Wcięcie oznacza, że linia należy do danego if albo else.

age = 20  # Zapisuje przykładowy wiek 20 lat.
if age >= 18:  # >= oznacza większe lub równe; tutaj warunek jest prawdziwy.
    print('You are an adult')  # Pokazuje, że osoba jest pełnoletnia.
else:  # Wykonuje tę część, gdy wiek jest mniejszy od 18.
    print('You are not an adult')  # Pokazuje, że osoba nie jest pełnoletnia.
