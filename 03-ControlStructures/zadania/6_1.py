# Krótka powtórka do lektury:
# if sprawdza warunek; jego wcięty kod wykona się tylko wtedy, gdy warunek jest prawdziwy.
# elif sprawdza kolejny warunek, jeżeli wcześniejsze warunki w tej samej konstrukcji nie zostały spełnione.
# else obsługuje pozostałe przypadki i nie wymaga własnego warunku.
# and wymaga prawdziwości obu warunków, or przynajmniej jednego, a not odwraca prawdę i fałsz.
# for przechodzi po elementach tekstu lub zakresu liczb; range(1, 4) dostarcza 1, 2 i 3.
# while powtarza kod tak długo, jak warunek jest prawdziwy; zwykle trzeba zmieniać sprawdzaną zmienną.
# break kończy najbliższą pętlę, a continue pomija jej pozostały kod i rozpoczyna następne powtórzenie.
