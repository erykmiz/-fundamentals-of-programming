# Zadanie 5.2: wyświetlanie kolejnych liczb za pomocą pętli while.
count = 0  # Ustawia początkową wartość licznika na zero.
while count < 5:  # Powtarza wcięty kod, dopóki licznik jest mniejszy od 5.
    print(count)  # Wyświetla bieżący licznik; kolejno pojawią się 0, 1, 2, 3 i 4.
    count += 1  # Zwiększa licznik o jeden, aby pętla ostatecznie mogła się zakończyć.
