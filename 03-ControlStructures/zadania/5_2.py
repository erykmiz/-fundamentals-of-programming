# Zadanie 5.2: wypisujemy liczby od 0 do 4.
# += 1 zwiększa licznik o jeden, żeby warunek while w końcu był fałszywy.

count = 0  # Ustawia licznik na 0.
while count < 5:  # Powtarza kod, dopóki count jest mniejsze od 5.
    print(count)  # Pokazuje bieżącą liczbę: 0, potem 1, aż do 4.
    count += 1  # Zwiększa licznik o 1.
