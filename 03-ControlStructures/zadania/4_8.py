# Zadanie 4.8: obliczenie ułamków 1/2, 1/3, ..., 1/10.
# Pokazujemy również 1/1, ponieważ taki pierwszy wiersz zawiera przykładowy wynik w poleceniu.
for i in range(1, 11):  # Pobiera kolejne mianowniki od 1 do 10 włącznie.
    print(f"1/{i} = {1 / i}")  # Dzieli 1 przez aktualny mianownik i wyświetla działanie z wynikiem.
